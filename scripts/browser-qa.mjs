import { chromium } from 'playwright';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const url = process.env.QA_URL || 'http://127.0.0.1:4173';
const works = JSON.parse(readFileSync('src/data/works.json','utf8'));
mkdirSync('docs/feishu-structure',{recursive:true});
const result = { viewports: [], videos: [], errors: [], network: {} };
const localChrome = process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({ headless: true, executablePath: process.env.QA_BROWSER_EXECUTABLE || (existsSync(localChrome) ? localChrome : undefined) });
result.browserVersion = browser.version();
try {
  const page = await browser.newPage({ viewport: { width:1440,height:900 } });
  page.on('pageerror', e => result.errors.push(e.message));
  await page.goto(url,{waitUntil:'networkidle'});
  for(const width of [1440,1024,768,390,360]) {
    await page.setViewportSize({width,height:900});
    await page.waitForTimeout(350);
    const layout = await page.evaluate(() => ({width:innerWidth,overflow:document.documentElement.scrollWidth>innerWidth,workIds:[...document.querySelectorAll('.project-chapters [data-work-id]')].map(el=>el.dataset.workId)}));
    assert.equal(layout.workIds.length,20);
    assert.equal(new Set(layout.workIds).size,20);
    assert.equal(layout.overflow,false); result.viewports.push(layout);
    if(width===1440||width===390) await page.screenshot({path:`docs/feishu-structure/${width===1440?'桌面':'手机'}预览.png`});
  }
  await page.setViewportSize({width:1440,height:900});
  await page.locator('#archive').scrollIntoViewIfNeeded();
  await page.getByRole('button',{name:/保司与通用模板\s*08/}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.collection-film').length===8);
  assert.equal(await page.locator('#work-W01').count(),0);
  await page.getByRole('button',{name:/全部作品\s*20/}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.collection-film').length===20);
  await page.locator('#work-W01-read').click();
  await page.waitForSelector('dialog[open]');
  assert.equal(await page.locator('.player-shell video').count(),0);
  await page.keyboard.press('Escape');
  await page.waitForSelector('dialog',{state:'detached'});
  await page.waitForFunction(()=>document.activeElement?.id==='work-W01-read');
  result.sequence='20 unique collection films; 4 source chapters and 6 complete project modules; manual case detail and restored focus';
  await page.locator('#archive').scrollIntoViewIfNeeded();
  await page.locator('.collection-filter button').filter({hasText:'个人创作练习'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.collection-film').length===4);
  const trigger = page.locator('#work-W19-title');
  await trigger.click();
  await page.waitForSelector('dialog[open]');
  assert.equal(await page.locator('dialog').count(),1);
  assert.equal(await page.locator('.player-shell video').count(),0);
  await page.keyboard.press('Escape');
  await page.waitForSelector('dialog',{state:'detached'});
  await page.waitForFunction(()=>document.activeElement?.id==='work-W19-title');
  assert.equal(await page.locator('.collection-filter button').filter({hasText:'个人创作练习'}).getAttribute('aria-pressed'),'true');
  assert.equal(await trigger.evaluate(el=>document.activeElement===el),true);
  await page.goForward(); await page.waitForSelector('dialog');
  assert.equal(await page.locator('.player-shell video').count(),0);
  await page.keyboard.press('Escape'); result.historyAndFocus='passed';
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(url,{waitUntil:'networkidle'});
  await page.locator('#work-W15-read').focus();
  await page.keyboard.press('Enter');
  await page.waitForSelector('dialog[open]');
  assert.equal(await page.locator('.player-shell video').count(),0);
  await page.keyboard.press('Escape');
  await page.waitForSelector('dialog',{state:'detached'});
  await page.waitForFunction(()=>document.activeElement?.id==='work-W15-read');
  result.reducedMotion='passed';
  for(const work of works) {
    await page.goto(`${url}/works/${work.slug}`,{waitUntil:'networkidle'});
    await page.locator('.player-start').click();
    await page.waitForFunction(()=>document.querySelector('video')?.readyState>=3&&!document.querySelector('video').paused,{},{timeout:15000});
    const initial = await page.locator('video').evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,volume:v.volume,muted:v.muted}));
    await page.locator('video').evaluate(v=>{v.currentTime=v.duration/2});
    await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-document.querySelector('video').duration/2)<3&&document.querySelector('video').readyState>=3,{},{timeout:15000});
    await page.locator('video').evaluate(v=>{v.currentTime=v.duration-.35});
    await page.waitForFunction(()=>document.querySelector('video').ended,{},{timeout:10000});
    result.videos.push({id:work.id,start:true,seek:true,end:true,...initial});
    console.log(`${work.id} 开始、进度、结尾通过`);
  }
  const context = await browser.newContext({viewport:{width:1440,height:900}});
  const perf = await context.newPage(); const cdp = await context.newCDPSession(perf);
  await cdp.send('Network.enable'); await cdp.send('Network.setCacheDisabled',{cacheDisabled:true});
  await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:100,downloadThroughput:1250000,uploadThroughput:1250000});
  await perf.addInitScript(()=>{window.__lcp=0;new PerformanceObserver(list=>{window.__lcp=list.getEntries().at(-1).startTime}).observe({type:'largest-contentful-paint',buffered:true})});
  await perf.goto(url,{waitUntil:'networkidle'}); await perf.waitForTimeout(500);
  result.network = await perf.evaluate(()=>({fcp:performance.getEntriesByType('paint').find(e=>e.name==='first-contentful-paint')?.startTime,lcp:window.__lcp,transferBytes:performance.getEntriesByType('resource').reduce((n,e)=>n+e.transferSize,0),videoRequests:performance.getEntriesByType('resource').filter(e=>e.name.endsWith('.mp4')).length}));
  Object.assign(result.network,{downloadMbps:10,latencyMs:100,coldCache:true});
  assert.equal(result.network.videoRequests,0);
  assert.ok(result.network.lcp<3000,`首屏 LCP ${result.network.lcp}ms 超出目标`);
  assert.ok(result.network.transferBytes<2_000_000);
  assert.deepEqual(result.errors,[]);
  console.log(JSON.stringify({screens:result.viewports.length,videos:result.videos.length,network:result.network}));
} finally {
  writeFileSync('docs/feishu-structure/浏览器验收.json',JSON.stringify(result,null,2)+'\n');
  await browser.close();
}
